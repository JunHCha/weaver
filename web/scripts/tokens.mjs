import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
export function generate() {
  const t = JSON.parse(
    readFileSync(new URL("../../design/tokens.json", import.meta.url), "utf8"),
  );
  const vars = { "color-scheme": "light" };
  const put = (key, value) => {
    vars[`--${key}`] = value;
  };
  const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
  for (const key of [
    "bg",
    "surface",
    "line",
    "ink",
    "muted",
    "indigo",
    "thread",
  ])
    put(key, t.color[key]);
  for (const [key, alias] of Object.entries({
    request: "req",
    decision: "dec",
    schedule: "sch",
    record: "rec",
    hollow: "hol",
  }))
    put(`c-${alias}`, t.color.kind[key].hex);
  put("tint", t.color.kind.request.tintPercent + "%");
  put("tint-rec", t.color.kind.record.tintPercent + "%");
  for (const [key, value] of Object.entries({
    hover: t.color.hover,
    "sel-bg": t.color.selected,
  })) {
    const rgb = value.hex
      .slice(1)
      .match(/../g)
      .map((c) => parseInt(c, 16));
    put(key, `rgba(${rgb.join(",")},${value.alpha})`);
  }
  for (const [key, values] of Object.entries(t.typography.family))
    put(
      `font-${key}`,
      values.map((v) => (v.includes(" ") ? `"${v}"` : v)).join(","),
    );
  for (const [group, prefix, unit] of [
    ["size", "fs", "px"],
    ["weight", "fw", ""],
    ["lineHeight", "lh", ""],
  ])
    for (const [key, v] of Object.entries(t.typography[group]))
      put(`${prefix}-${kebab(key)}`, v + unit);
  for (const [group, prefix, unit] of [
    ["radius", "r", "px"],
    ["spacing", "sp", "px"],
    ["layout", "ly", "px"],
    ["stroke", "sw", ""],
    ["opacity", "op", ""],
  ])
    for (const [key, v] of Object.entries(t[group]))
      if (key !== "pulseTail") put(`${prefix}-${kebab(key)}`, v + unit);
  put("sat-card-dim", t.filter.cardDimSaturate);
  for (const key of [
    "hover",
    "panelSlide",
    "flipSlide",
    "flipFadeOut",
    "flipFadeIn",
  ]) {
    put(`dur-${kebab(key)}`, t.motion[key].duration + "ms");
    put(`ease-${kebab(key)}`, t.motion[key].easing);
  }
  for (const key of ["min", "floor", "max"])
    put(`dur-pulse-hop-${key}`, t.motion.pulseHop[key]);
  for (const key of ["pause", "flash", "runMax"])
    put(
      `dur-pulse-${kebab(key)}`,
      t.motion[`pulse${key[0].toUpperCase()}${key.slice(1)}`],
    );
  put("sz-pulse-tail", t.stroke.pulseTail);
  return (
    "/* Generated by scripts/tokens.mjs from design/tokens.json. */\n:root {\n" +
    Object.entries(vars)
      .map(([k, v]) => `  ${k}: ${v};`)
      .join("\n") +
    "\n}\n"
  );
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  writeFileSync(
    new URL("../src/styles/tokens.css", import.meta.url),
    generate(),
  );
