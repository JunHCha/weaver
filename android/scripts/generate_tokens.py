#!/usr/bin/env python3
"""Generate committed Android tokens. Run from any directory; Python stdlib only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = json.loads((ROOT / "design/tokens.json").read_text())
UI = ROOT / "android/app/src/main/kotlin/io/github/junhcha/weaver/ui"
RES = ROOT / "android/app/src/main/res/values"


def flatten(value, path=""):
    if isinstance(value, dict):
        return {k: v for key, child in value.items() if not key.startswith("$")
                for k, v in flatten(child, f"{path}.{key}" if path else key).items()}
    if isinstance(value, list):
        return {k: v for i, child in enumerate(value)
                for k, v in flatten(child, f"{path}.{i}").items()}
    return {path: str(value)}


def quoted(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


lines = ["// Generated by android/scripts/generate_tokens.py. Do not edit.",
         "package io.github.junhcha.weaver.ui", "",
         "import androidx.compose.ui.graphics.Color", "",
         "object WeaverTokens {", "    val values: Map<String, String> = mapOf("]
for key, value in flatten(TOKENS).items():
    lines.append(f"        {quoted(key)} to {quoted(value)},")
lines += ["    )", "", "    fun number(path: String): Float = values.getValue(path).toFloat()",
          '    private fun color(path: String): Color = Color((0xFF000000L or values.getValue(path).removePrefix("#").toLong(16)).toInt())']
for name, value in TOKENS["color"].items():
    if isinstance(value, str):
        lines.append(f'    val {name}: Color get() = color("color.{name}")')
    elif "hex" in value:
        lines.append(f'    val {name}: Color get() = color("color.{name}.hex").copy(alpha = number("color.{name}.alpha"))')
lines += ["", "    data class Kind(val color: Color, val tintPercent: Float, val dashed: Boolean)",
          '    fun kind(name: String): Kind = Kind(color("color.kind.$name.hex"),',
          '        number("color.kind.$name.tintPercent"), values.getValue("color.kind.$name.band") == "dashed")']
for name in TOKENS["color"]["kind"]:
    lines.append(f'    val {name}: Kind get() = kind("{name}")')
lines += ["}", ""]
(UI / "WeaverTokens.kt").write_text("\n".join(lines))
colors = {f"weaver_{key}": value for key, value in TOKENS["color"].items() if isinstance(value, str)}
colors.update({f"weaver_{key}": value["hex"] for key, value in TOKENS["color"]["kind"].items()})
xml = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by android/scripts/generate_tokens.py. -->', '<resources>']
xml += [f'    <color name="{key}">{value}</color>' for key, value in colors.items()]
xml += ['    <color name="ic_launcher_background">@color/weaver_bg</color>', '</resources>', '']
(RES / "colors.xml").write_text("\n".join(xml))
